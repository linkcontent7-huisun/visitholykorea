import { describe, expect, it } from 'vitest';
import { telHref } from './phone';

describe('전화 단추는 첫 번호만 (점검 S2, 2026-11-22)', () => {
  it.each([
    ['(031)674-1256~7', 'tel:0316741256'],
    ['(031)246-8844,5', 'tel:0312468844'],
    ['(063)263-1004/5', 'tel:0632631004'],
    ['(033)743-1006 원동성당', 'tel:0337431006'],
    ['(064) 721-2343 (사무실)', 'tel:0647212343'],
    ['010-1234-5678', 'tel:01012345678'],
    ['02-740-9707', 'tel:027409707'],
    ['1588-1234', 'tel:15881234'],
    ['+82-2-740-9707', 'tel:+8227409707'],
  ])('%s → %s', (raw, want) => expect(telHref(raw)).toBe(want));

  it('번호가 없으면 단추를 걸지 않는다', () => {
    expect(telHref('문의는 본당 사무실로')).toBeNull();
    expect(telHref(null)).toBeNull();
  });
});
